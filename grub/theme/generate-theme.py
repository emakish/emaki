"""Write the GRUB menu theme: one theme file and one set of pixmaps per scale.

GRUB themes place components in percentages, but fonts and pixmaps have fixed
pixel sizes. The menu generator therefore picks the scale from the mode GRUB
drew in (installer/emaki_installer/boot.py: menu_theme); the layout numbers
live in grub_screen.py, shared with the disk-password pictures. Colours come from
tokens.toml. Only the Python standard library is needed, so the output can be
checked anywhere; the committed files are the shipped ones.
"""

import argparse
from pathlib import Path
import struct
import sys
import tomllib
import zlib

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'installer'))
from emaki_installer import grub_screen as layout  # noqa: E402

PIECES = ('nw', 'n', 'ne', 'w', 'c', 'e', 'sw', 's', 'se')


def png(width, height, pixels):
    """Uncompressed-filter RGBA PNG; GRUB's reader handles 8-bit RGBA."""
    raw = b''.join(b'\0' + bytes(pixels[y * width * 4:(y + 1) * width * 4]) for y in range(height))

    def chunk(name, body):
        return struct.pack('>I', len(body)) + name + body + struct.pack('>I', zlib.crc32(name + body))

    return (b'\x89PNG\r\n\x1a\n'
            + chunk(b'IHDR', struct.pack('>IIBBBBB', width, height, 8, 6, 0, 0, 0))
            + chunk(b'IDAT', zlib.compress(raw, 9)) + chunk(b'IEND', b''))


def coverage(x, y, radius):
    """Fraction of pixel (x, y) inside a quarter circle centred at (radius, radius)."""
    inside = 0
    for sy in range(4):
        for sx in range(4):
            dx = radius - (x + (sx + .5) / 4)
            dy = radius - (y + (sy + .5) / 4)
            inside += dx <= 0 or dy <= 0 or dx * dx + dy * dy <= radius * radius
    return inside / 16


def box(color, alpha, radius):
    """Nine pieces of a rounded rectangle; the corner size is also the padding."""
    rgb = tuple(bytes.fromhex(color))
    corner = []
    for y in range(radius):
        for x in range(radius):
            corner += [*rgb, round(255 * alpha * coverage(x, y, radius))]

    def mirrored(flip_x, flip_y):
        result = []
        for y in range(radius):
            for x in range(radius):
                source = ((radius - 1 - y) if flip_y else y) * radius + ((radius - 1 - x) if flip_x else x)
                result += corner[source * 4:source * 4 + 4]
        return result

    solid = [*rgb, round(255 * alpha)]
    return {
        'nw': png(radius, radius, mirrored(False, False)),
        'ne': png(radius, radius, mirrored(True, False)),
        'sw': png(radius, radius, mirrored(False, True)),
        'se': png(radius, radius, mirrored(True, True)),
        'n': png(1, radius, solid * radius), 's': png(1, radius, solid * radius),
        'w': png(radius, 1, solid * radius), 'e': png(radius, 1, solid * radius),
        'c': png(1, 1, solid),
    }


def theme(scale, colors):
    # GRUB draws the selection's corner pieces outside the item's content box, so
    # the content is the row minus both corners and the spacing makes room for them:
    # each selection is exactly one row high, rows are one row plus the gap apart.
    s = layout.SCALES[scale]
    item_font = f'{layout.FONT_FAMILY} {s["item"]}'
    hint_font = f'{layout.FONT_FAMILY} {s["hint"]}'
    left, top, width, height = layout.PANEL
    return f'''# Copyright (C) 2026 Artur Yakymenko
# SPDX-License-Identifier: GPL-3.0-or-later
# Generated by grub/theme/generate-theme.py for the {scale}% scale; do not edit.
title-text: ""
desktop-image: "background.png"
desktop-image-scale-method: "crop"
desktop-color: "#{colors['background']}"
terminal-font: "Unifont Regular 16"

+ boot_menu {{
    left = {left}%
    top = {top}%
    width = {width}%
    height = {height}%
    menu_pixmap_style = "{scale}/menu_*.png"
    selected_item_pixmap_style = "{scale}/select_*.png"
    item_font = "{item_font}"
    selected_item_font = "{item_font}"
    item_color = "#{colors['text']}"
    selected_item_color = "#{colors['on_accent']}"
    item_height = {s["row"] - 2 * s["select_radius"]}
    item_padding = {s["inset"]}
    item_spacing = {2 * s["select_radius"] + s["gap"]}
    icon_width = 0
    icon_height = 0
    item_icon_space = 0
    scrollbar = false
}}

+ label {{
    left = 0
    top = {layout.HINT_TOP}%
    width = 100%
    height = {s["hint_row"]}
    align = "center"
    font = "{hint_font}"
    color = "#{colors['text']}"
    text = "{layout.HINT}"
}}

+ label {{
    id = "__timeout__"
    left = 0
    top = {layout.TIMEOUT_TOP}%
    width = 100%
    height = {s["hint_row"]}
    align = "center"
    font = "{hint_font}"
    color = "#{colors['text']}"
    text = "{layout.TIMEOUT}"
}}
'''


def files(colors):
    result = {}
    for scale, s in layout.SCALES.items():
        result[f'theme-{scale}.txt'] = theme(scale, colors).encode()
        for prefix, (color, alpha, radius) in (
                ('menu', (colors['surface'], layout.PANEL_ALPHA, s['panel_radius'])),
                ('select', (colors['accent'], 1.0, s['select_radius']))):
            for piece, data in box(color, alpha, radius).items():
                result[f'{scale}/{prefix}_{piece}.png'] = data
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=Path(__file__).resolve().parent)
    parser.add_argument('--check', action='store_true', help='compare regenerated bytes without writing')
    args = parser.parse_args()
    colors = tomllib.loads((ROOT / 'tokens.toml').read_text())['color']
    for name, data in files(colors).items():
        path = args.output / name
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                raise SystemExit(f'GRUB theme needs regeneration: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print('GRUB theme is current.' if args.check else 'Wrote the GRUB theme.')


if __name__ == '__main__':
    main()
